import AppKit
import Foundation

/// Small seam over NSPasteboard so the monitor is unit-testable.
public protocol PasteboardReading {
  var changeCount: Int { get }
  var types: [String] { get }
  func string() -> String?
  func pngData() -> Data?
  /// Raw PNG or TIFF bytes, without any conversion; the monitor converts them off the main thread.
  func imageData() -> PasteboardImage?
  var frontmostAppBundleID: String? { get }
}

extension PasteboardReading {
  public func imageData() -> PasteboardImage? { pngData().map(PasteboardImage.png) }
}

public struct SystemPasteboard: PasteboardReading {
  public init() {}
  public var changeCount: Int { NSPasteboard.general.changeCount }
  public var types: [String] { NSPasteboard.general.types?.map(\.rawValue) ?? [] }
  public func string() -> String? { NSPasteboard.general.string(forType: .string) }
  /// Converts synchronously; the monitor uses `imageData()` instead.
  public func pngData() -> Data? { imageData().flatMap { ImageNormalizer().png(from: $0) } }
  public func imageData() -> PasteboardImage? {
    let pb = NSPasteboard.general
    if let png = pb.data(forType: .png) { return .png(png) }
    return pb.data(forType: .tiff).map(PasteboardImage.tiff)
  }
  public var frontmostAppBundleID: String? { NSWorkspace.shared.frontmostApplication?.bundleIdentifier }
}

/// Polls the pasteboard on the main thread, but only reads it there: secret scanning and image
/// conversion run on a serial background queue, and entries are delivered on the main thread in
/// copy order. Text longer than `maxTextLength` is not recorded at all: it cannot be scanned within
/// a bounded time, and recording it unscanned could keep a secret.
///
/// With `ocr` set, each image entry is delivered at once (with `ocrText` nil) and its text is
/// recognised afterwards, one image at a time and never on the main thread, so polling and later
/// copies are not held up. The recognised text is scanned like copied text; the result arrives
/// through `onOCR`, with findings and an expiry when it holds a secret, and `scanned` false when the
/// image could not be checked (recognition failed or ran out of time). Every recognition is bounded
/// by `ocrTimeBudget`, counted from the copy (time spent queued included); at most `maxOCRBacklog`
/// images wait, and images beyond that are delivered without OCR (`awaitingOCR` false). An image
/// without a successful scan is never persisted by `HistoryStore`; it stays in memory only.
@MainActor
public final class ClipboardMonitor {
  /// UTF-16 units; matches the detector's scan budget.
  public static let defaultMaxTextLength = SecretDetector.maxScanLength

  public static let skippedTypePrefixes = [
    "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword", SecretPasteboardWriter.internalType,
    // Our marker under the bundle ID used before the rename; a stale pasteboard may still carry it.
    "com.example.copyhistory.internal",
    // Legacy "don't record" markers from nspasteboard.org.
    "de.petermaurer.TransientPasteboardType", "com.typeit4me.clipping", "Pasteboard generator type",
  ]

  public var ignoredApps: Set<String>
  /// Seconds until a flagged entry expires; 0 (or negative) means flagged entries never expire.
  public var secretExpiry: TimeInterval
  public var onEntry: ((ClipboardEntry) -> Void)?
  /// Like `onEntry` (both are called), plus whether an `onOCR` update for the entry will follow.
  public var onCapture: ((ClipboardEntry, _ awaitingOCR: Bool) -> Void)?
  /// The pasteboard `changeCount` the entry being delivered was read from; set only while `onEntry`
  /// and `onCapture` run, nil otherwise. Comparing it with the current `changeCount` tells whether
  /// the pasteboard still holds that very copy (conversion runs off the main thread, so a newer copy
  /// may already be there).
  public private(set) var capturingChangeCount: Int?
  /// The text recognised in an image entry delivered earlier; exactly one per `awaitingOCR` entry.
  public var onOCR: ((OCRUpdate) -> Void)?
  /// nil disables OCR. Read at copy time.
  public var ocr: (any OCRRecognizing)?
  /// Hard limit for one image, from its copy to its `onOCR` update; past it the update says `scanned` false.
  public var ocrTimeBudget: TimeInterval = VisionOCR.defaultTimeBudget + 5
  public var maxOCRBacklog = 4
  /// Characters of recognised text kept on the entry; the whole text is scanned before the cut.
  public var maxOCRTextLength = ClipboardMonitor.defaultMaxOCRTextLength
  nonisolated public static let defaultMaxOCRTextLength = 10_000
  public var maxTextLength = ClipboardMonitor.defaultMaxTextLength
  public var imageNormalizer = ImageNormalizer()

  private let pasteboard: PasteboardReading
  private let detector: SecretDetecting
  private let interval: TimeInterval
  private let now: () -> Date
  private var lastChangeCount: Int
  private var ownChangeCounts: Set<Int> = []
  private var timer: Timer?
  private let workQueue = DispatchQueue(label: "CopyHistory.ClipboardMonitor.work", qos: .userInitiated)
  private var pending = 0
  private var idleWaiters: [CheckedContinuation<Void, Never>] = []
  private struct OCRJob { let entry: ClipboardEntry; let png: Data; let ocr: any OCRRecognizing
                          let deadline: Date; let expiry: TimeInterval }
  private var ocrBacklog: [OCRJob] = []
  private var ocrRunning = false

  public init(pasteboard: PasteboardReading = SystemPasteboard(),
              detector: SecretDetecting = SecretDetector(),
              interval: TimeInterval = 0.5,
              secretExpiry: TimeInterval = 60,
              ignoredApps: Set<String> = [],
              now: @escaping () -> Date = Date.init) {
    self.pasteboard = pasteboard; self.detector = detector; self.interval = interval
    self.secretExpiry = secretExpiry; self.ignoredApps = ignoredApps; self.now = now
    self.lastChangeCount = pasteboard.changeCount  // existing contents are not captured
  }

  public func start() {
    guard timer == nil else { return }
    let t = Timer(timeInterval: interval, repeats: true) { [weak self] _ in
      MainActor.assumeIsolated { self?.poll() }
    }
    RunLoop.main.add(t, forMode: .common)
    timer = t
  }

  public func stop() { timer?.invalidate(); timer = nil }

  /// Delivers entries and OCR updates to `store`. Use instead of `onEntry = { store.add($0) }`.
  public func connect(to store: HistoryStore) {
    onCapture = { entry, awaiting in _ = store.add(entry, awaitingOCR: awaiting) }
    onOCR = { store.applyOCR($0) }
  }

  /// Call right after the app writes to the pasteboard, passing the resulting changeCount.
  public func registerOwnWrite(changeCount: Int) { ownChangeCounts.insert(changeCount) }

  /// Resumes once every captured copy has been scanned/converted and delivered (for tests).
  public func waitUntilIdle() async {
    guard pending > 0 else { return }
    await withCheckedContinuation { idleWaiters.append($0) }
  }

  /// One polling step; exposed for tests. Delivery through `onEntry` happens asynchronously.
  public func poll() {
    let count = pasteboard.changeCount
    guard count != lastChangeCount else { return }
    lastChangeCount = count
    if ownChangeCounts.remove(count) != nil { return }
    ownChangeCounts = ownChangeCounts.filter { $0 > count }

    let types = pasteboard.types
    if types.contains(where: { t in Self.skippedTypePrefixes.contains { t.hasPrefix($0) } }) { return }
    let app = pasteboard.frontmostAppBundleID
    if let app, ignoredApps.contains(app) { return }

    let date = now()
    let rawText = pasteboard.string()
    // O(1) for pasteboard strings; checked before any O(n) work such as trimming.
    if let rawText, rawText.utf16.count > maxTextLength { return }
    let text = rawText.flatMap { $0.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty ? nil : $0 }
    let image = text == nil ? pasteboard.imageData() : nil
    // The reads above are not atomic: if the pasteboard changed meanwhile (e.g. a password manager
    // wrote a ConcealedType password), the payload may belong to a generation whose types we never
    // checked. Drop it; the next poll sees the new changeCount and re-checks its types.
    guard pasteboard.changeCount == count else { return }
    guard text != nil || image != nil else { return }

    let expiry = secretExpiry
    let detector = detector
    let normalizer = imageNormalizer
    let recognizer = ocr
    pending += 1
    workQueue.async {
      var entry: ClipboardEntry?
      if let text {
        let findings = detector.scan(text)
        let expires = findings.isEmpty || expiry <= 0 ? nil : date.addingTimeInterval(expiry)
        entry = ClipboardEntry(kind: .text, text: text, sourceApp: app, now: date, findings: findings,
                               expiresAt: expires)
      } else if let image, let png = normalizer.png(from: image) {
        entry = ClipboardEntry(kind: .image, imagePNG: png, sourceApp: app, now: date)
      }
      // Main-queue FIFO keeps entries in copy order.
      DispatchQueue.main.async { [weak self] in
        MainActor.assumeIsolated { self?.finish(entry, changeCount: count, ocr: recognizer, expiry: expiry) }
      }
    }
  }

  private func finish(_ entry: ClipboardEntry?, changeCount: Int, ocr: (any OCRRecognizing)?, expiry: TimeInterval) {
    if let entry {
      // OCR starts only after the entry is delivered, so its update can never overtake it.
      var job: OCRJob?
      if let ocr, entry.kind == .image, let png = entry.imagePNG, ocrBacklog.count < maxOCRBacklog {
        job = OCRJob(entry: entry, png: png, ocr: ocr, deadline: entry.firstCopiedAt.addingTimeInterval(ocrTimeBudget),
                     expiry: expiry)
      }
      capturingChangeCount = changeCount
      onEntry?(entry)
      onCapture?(entry, job != nil)
      capturingChangeCount = nil
      if let job { pending += 1; ocrBacklog.append(job); runNextOCR() }
    }
    settle()
  }

  private func runNextOCR() {
    guard !ocrRunning, !ocrBacklog.isEmpty else { return }
    ocrRunning = true
    let job = ocrBacklog.removeFirst()
    let detector = detector
    let maxLength = maxOCRTextLength
    // The deadline counts from the copy time on the monitor's clock; map it to real time from now.
    let remaining = job.deadline.timeIntervalSince(now())
    Task.detached(priority: .utility) { [self] in
      let result = await OCRDeadline.scan(job.ocr, png: job.png, within: remaining)
      let (text, findings, scanned) = OCRText.process(result, maxLength: maxLength, detector: detector)
      let expires = findings.isEmpty || job.expiry <= 0 ? nil : job.entry.firstCopiedAt.addingTimeInterval(job.expiry)
      let update = OCRUpdate(entryID: job.entry.id, imagePNG: job.png, scanned: scanned, ocrText: text,
                             findings: findings, expiresAt: expires)
      await self.finishOCR(update)
    }
  }

  private func finishOCR(_ update: OCRUpdate) {
    onOCR?(update)
    ocrRunning = false
    runNextOCR()
    settle()
  }

  private func settle() {
    pending -= 1
    if pending == 0 {
      let waiters = idleWaiters
      idleWaiters = []
      waiters.forEach { $0.resume() }
    }
  }
}
