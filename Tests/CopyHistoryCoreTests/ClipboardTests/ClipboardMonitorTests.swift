final class FakePasteboard: PasteboardReading, @unchecked Sendable {
  var changeCount = 0
  var types: [String] = ["public.utf8-plain-text"]
  var text: String?
  var png: Data?
  var image: PasteboardImage?
  var frontmostAppBundleID: String? = "com.example.app"
  /// Runs once inside the next `string()` call, to simulate the pasteboard changing mid-poll.
  var onNextStringRead: (() -> Void)?
  func string() -> String? {
    if let hook = onNextStringRead { onNextStringRead = nil; hook() }
    return text
  }
  func pngData() -> Data? { png }
  func imageData() -> PasteboardImage? { image ?? png.map(PasteboardImage.png) }
  func copy(_ s: String, types: [String] = ["public.utf8-plain-text"]) {
    text = s; png = nil; image = nil; self.types = types; changeCount += 1
  }
}

/// A solid-colour image encoded with ImageIO.
func makeImage(width: Int, height: Int, type: String) -> Data {
  let ctx = CGContext(data: nil, width: width, height: height, bitsPerComponent: 8, bytesPerRow: 0,
                      space: CGColorSpaceCreateDeviceRGB(), bitmapInfo: CGImageAlphaInfo.premultipliedLast.rawValue)!
  ctx.setFillColor(red: 0.2, green: 0.4, blue: 0.8, alpha: 1)
  ctx.fill(CGRect(x: 0, y: 0, width: width, height: height))
  let out = NSMutableData()
  let dest = CGImageDestinationCreateWithData(out as CFMutableData, type as CFString, 1, nil)!
  CGImageDestinationAddImage(dest, ctx.makeImage()!, nil)
  CGImageDestinationFinalize(dest)
  return out as Data
}

func pixelSize(_ png: Data) -> (Int, Int)? {
  guard let src = CGImageSourceCreateWithData(png as CFData, nil),
        let p = CGImageSourceCopyPropertiesAtIndex(src, 0, nil) as? [CFString: Any],
        let w = p[kCGImagePropertyPixelWidth] as? Int, let h = p[kCGImagePropertyPixelHeight] as? Int else { return nil }
  return (w, h)
}

let tinyPNG = makeImage(width: 2, height: 2, type: "public.png")

/// Records which thread scans and can stall, to prove scanning is off the main thread.
final class SpyDetector: SecretDetecting, @unchecked Sendable {
  let delay: TimeInterval
  private let lock = NSLock()
  private var _onMain: [Bool] = []
  var scannedOnMain: [Bool] { lock.lock(); defer { lock.unlock() }; return _onMain }
  init(delay: TimeInterval) { self.delay = delay }
  func scan(_ text: String) -> [SecretFinding] {
    lock.lock(); _onMain.append(Thread.isMainThread); lock.unlock()
    Thread.sleep(forTimeInterval: delay)
    return SecretDetector().scan(text)
  }
  func mask(_ text: String, findings: [SecretFinding]) -> String { SecretDetector().mask(text, findings: findings) }
}

private func seconds(_ body: () -> Void) -> Double {
  let start = DispatchTime.now().uptimeNanoseconds
  body()
  return Double(DispatchTime.now().uptimeNanoseconds - start) / 1e9
}

@MainActor @Suite struct ClipboardMonitorTests {
  func make(_ pb: FakePasteboard, ignored: Set<String> = []) -> (ClipboardMonitor, () -> [ClipboardEntry]) {
    let m = ClipboardMonitor(pasteboard: pb, ignoredApps: ignored, now: { Date(timeIntervalSince1970: 1000) })
    var got: [ClipboardEntry] = []
    m.onEntry = { got.append($0) }
    return (m, { got })
  }

  @Test func emitsTextWithSourceApp() async {
    let pb = FakePasteboard(); let (m, got) = make(pb)
    pb.copy("hello"); m.poll(); m.poll()
    await m.waitUntilIdle()
    #expect(got().count == 1)
    #expect(got()[0].text == "hello" && got()[0].sourceApp == "com.example.app")
    #expect(got()[0].findings.isEmpty && got()[0].expiresAt == nil)
  }

  @Test func existingContentsNotCaptured() async {
    let pb = FakePasteboard(); pb.copy("old")
    let (m, got) = make(pb); m.poll()
    await m.waitUntilIdle()
    #expect(got().isEmpty)
  }

  @Test func skipsConcealedTransientAutoGeneratedAndOnePassword() async {
    let pb = FakePasteboard(); let (m, got) = make(pb)
    for t in ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
              "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"] {
      pb.copy("secret", types: ["public.utf8-plain-text", t]); m.poll()
    }
    await m.waitUntilIdle()
    #expect(got().isEmpty)
  }

  @Test func ignoredApps() async {
    let pb = FakePasteboard(); let (m, got) = make(pb, ignored: ["com.example.app"])
    pb.copy("x"); m.poll()
    await m.waitUntilIdle()
    #expect(got().isEmpty)
    m.ignoredApps = []
    pb.copy("y"); m.poll()
    await m.waitUntilIdle()
    #expect(got().count == 1)
  }

  @Test func ignoresOwnWrites() async {
    let pb = FakePasteboard(); let (m, got) = make(pb)
    pb.copy("mine"); m.registerOwnWrite(changeCount: pb.changeCount); m.poll()
    pb.copy("theirs"); m.poll()
    await m.waitUntilIdle()
    #expect(got().map(\.text) == ["theirs"])
  }

  @Test func flagsSecretsWithExpiry() async {
    let pb = FakePasteboard(); let (m, got) = make(pb)
    pb.copy("sk-proj-FAKEFAKEFAKEFAKEFAKE1234"); m.poll()
    await m.waitUntilIdle()
    #expect(got()[0].findings.map(\.category) == [.openAIKey])
    #expect(got()[0].expiresAt == Date(timeIntervalSince1970: 1060))
    m.secretExpiry = 5
    pb.copy("4111111111111111"); m.poll()
    await m.waitUntilIdle()
    #expect(got()[1].expiresAt == Date(timeIntervalSince1970: 1005))
  }

  @Test func readsPNG() async {
    let pb = FakePasteboard(); let (m, got) = make(pb)
    pb.png = tinyPNG; pb.text = nil; pb.changeCount += 1; m.poll()
    await m.waitUntilIdle()
    #expect(got().count == 1 && got()[0].kind == .image && got()[0].imagePNG == tinyPNG)
  }

  @Test func zeroOrNegativeExpiryMeansNever() async {
    let pb = FakePasteboard(); let (m, got) = make(pb)
    m.secretExpiry = 0
    pb.copy("sk-proj-FAKEFAKEFAKEFAKEFAKE1234"); m.poll()
    m.secretExpiry = -1
    pb.copy("4111111111111111"); m.poll()
    await m.waitUntilIdle()
    #expect(got().count == 2)
    #expect(got().allSatisfy { !$0.findings.isEmpty && $0.expiresAt == nil })
  }

  @Test func pasteboardChangingMidPollDoesNotRecordConcealedPassword() async {
    let pb = FakePasteboard(); let (m, got) = make(pb)
    pb.copy("ordinary text")
    pb.onNextStringRead = {
      pb.copy("FakeP@ssw0rd-not-real", types: ["public.utf8-plain-text", "org.nspasteboard.ConcealedType"])
    }
    m.poll(); m.poll(); m.poll()
    await m.waitUntilIdle()
    #expect(got().isEmpty)
    // A normal copy afterwards is still recorded.
    pb.copy("after"); m.poll()
    await m.waitUntilIdle()
    #expect(got().map(\.text) == ["after"])
  }

  @Test func skipsLegacyTransientMarkers() async {
    let pb = FakePasteboard(); let (m, got) = make(pb)
    for t in ["de.petermaurer.TransientPasteboardType", "com.typeit4me.clipping", "Pasteboard generator type"] {
      pb.copy("otp 123456", types: ["public.utf8-plain-text", t]); m.poll()
    }
    await m.waitUntilIdle()
    #expect(got().isEmpty)
  }

  // MARK: - Responsiveness: nothing heavy on the main thread

  @Test func tenMegabyteCopyDoesNotFreezeAndIsNotRecorded() async {
    let pb = FakePasteboard(); let (m, got) = make(pb)
    // Decomposed accents are the slowest input for the detector (~12 s for 10 MB before the cap).
    pb.copy(String(repeating: "a\u{301}", count: 5_000_000) + " sk-proj-FAKEFAKEFAKEFAKEFAKE1234")
    #expect(seconds { m.poll() } < 0.5)
    await m.waitUntilIdle()
    #expect(got().isEmpty)  // too big to scan, so never recorded unscanned
    pb.copy("small"); m.poll()
    await m.waitUntilIdle()
    #expect(got().map(\.text) == ["small"])
  }

  @Test func scanningRunsOffTheMainThreadAndKeepsCopyOrder() async {
    let pb = FakePasteboard()
    let spy = SpyDetector(delay: 0.3)
    let m = ClipboardMonitor(pasteboard: pb, detector: spy, now: { Date(timeIntervalSince1970: 1000) })
    var got: [ClipboardEntry] = []
    m.onEntry = { got.append($0) }
    let elapsed = seconds {
      pb.copy("first"); m.poll()
      pb.copy("sk-proj-FAKEFAKEFAKEFAKEFAKE1234"); m.poll()
      pb.copy("third"); m.poll()
    }
    #expect(elapsed < 0.25)  // three 0.3 s scans did not run inline
    await m.waitUntilIdle()
    #expect(got.map(\.text) == ["first", "sk-proj-FAKEFAKEFAKEFAKEFAKE1234", "third"])
    #expect(got[1].findings.map(\.category) == [.openAIKey] && got[1].expiresAt == Date(timeIntervalSince1970: 1060))
    #expect(spy.scannedOnMain == [false, false, false])
  }

  @Test func tiffIsConvertedToPNGOffTheMainThread() async throws {
    let pb = FakePasteboard(); let (m, got) = make(pb)
    pb.text = nil; pb.image = .tiff(makeImage(width: 40, height: 30, type: "public.tiff")); pb.changeCount += 1
    m.poll()
    #expect(got().isEmpty)  // converted later, not inline in poll()
    await m.waitUntilIdle()
    let png = try #require(got().first?.imagePNG)
    #expect(png.starts(with: [0x89, 0x50, 0x4E, 0x47]))
    #expect(pixelSize(png)! == (40, 30))
  }

  @Test func oversizedImagesAreDownscaledOrDropped() async throws {
    let pb = FakePasteboard(); let (m, got) = make(pb)
    m.imageNormalizer = ImageNormalizer(maxPixelSide: 50)
    pb.text = nil; pb.image = .tiff(makeImage(width: 200, height: 100, type: "public.tiff")); pb.changeCount += 1
    m.poll(); await m.waitUntilIdle()
    let png = try #require(got().first?.imagePNG)
    #expect(pixelSize(png)! == (50, 25))

    // Raw input beyond the read cap is never decoded at all.
    m.imageNormalizer = ImageNormalizer(maxInputBytes: 10)
    pb.image = .png(tinyPNG); pb.changeCount += 1
    m.poll(); await m.waitUntilIdle()
    #expect(got().count == 1)
  }

  @Test func defaultImageLimitsAreBounded() {
    let n = ImageNormalizer()
    #expect(n.maxBytes <= 25_000_000 && n.maxPixelSide <= 8192)
    #expect(ClipboardMonitor.defaultMaxTextLength == SecretDetector.maxScanLength)
  }
}
